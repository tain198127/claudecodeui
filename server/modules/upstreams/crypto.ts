/**
 * Symmetric encryption for stored upstream auth tokens.
 *
 * The key is derived from the install's existing `jwt_secret` rather than a new
 * secret of its own, so the ciphertext a server writes is the ciphertext it can
 * read back after a restart with no extra provisioning or key file to manage.
 *
 * `decryptSecret` never throws: a token that fails to decrypt is reported as
 * `null` and every caller treats that as "no upstream configured", which keeps a
 * damaged secret from taking down the chat path it is consulted on.
 */

import crypto from 'crypto';

import { appConfigDb } from '@/modules/database/index.js';

const ALGORITHM = 'aes-256-gcm';
const KEY_LENGTH = 32;
const IV_LENGTH = 12;
const AUTH_TAG_LENGTH = 16;

/**
 * Fixed scrypt salt. A per-install salt would add nothing here: the input is
 * already a 64-byte random secret generated by this install, not a password.
 */
const KEY_SALT = 'cloudcli-upstreams-v1';

/**
 * Derives the 32-byte data key from the application's JWT secret.
 *
 * The secret is created on first use, so an install that has never signed a
 * token still ends up with a stable key rather than an error.
 */
const deriveKey = (): Buffer => crypto.scryptSync(
  appConfigDb.getOrCreateJwtSecret(),
  KEY_SALT,
  KEY_LENGTH,
);

/**
 * Encrypts a secret, returning `base64(iv | authTag | ciphertext)`.
 *
 * The IV is random per call so encrypting the same token twice yields different
 * ciphertext, and the tag is stored alongside the ciphertext because GCM
 * verification needs both to reject a tampered payload.
 */
export const encryptSecret = (plain: string): string => {
  const iv = crypto.randomBytes(IV_LENGTH);
  const cipher = crypto.createCipheriv(ALGORITHM, deriveKey(), iv);
  const ciphertext = Buffer.concat([cipher.update(plain, 'utf8'), cipher.final()]);

  return Buffer.concat([iv, cipher.getAuthTag(), ciphertext]).toString('base64');
};

/**
 * Decrypts a value produced by `encryptSecret`.
 *
 * Returns null for a missing, malformed, truncated, or tampered payload instead
 * of throwing. The message is deliberately generic: it is what callers surface,
 * and a GCM failure detail would describe the ciphertext.
 */
export const decryptSecret = (encrypted: string | null | undefined): string | null => {
  if (!encrypted) {
    return null;
  }

  try {
    const payload = Buffer.from(encrypted, 'base64');
    // A payload has to carry at least an IV and a tag. The ciphertext itself may
    // be empty — that is a valid GCM output for an empty secret — so the
    // boundary is strict rather than inclusive.
    if (payload.length < IV_LENGTH + AUTH_TAG_LENGTH) {
      return null;
    }

    const iv = payload.subarray(0, IV_LENGTH);
    const authTag = payload.subarray(IV_LENGTH, IV_LENGTH + AUTH_TAG_LENGTH);
    const ciphertext = payload.subarray(IV_LENGTH + AUTH_TAG_LENGTH);

    const decipher = crypto.createDecipheriv(ALGORITHM, deriveKey(), iv);
    decipher.setAuthTag(authTag);

    return Buffer.concat([decipher.update(ciphertext), decipher.final()]).toString('utf8');
  } catch {
    return null;
  }
};
